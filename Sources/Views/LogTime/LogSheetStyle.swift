// MARK: Layout

/// Wrapping row of chips (the editors and the quick picks).
struct LogChipFlow: Layout {
    var spacing: CGFloat = 8

    func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
        arrange(width: proposal.width ?? 10_000, subviews: subviews).size
    }

    func placeSubviews(in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) {
        let layout = arrange(width: bounds.width, subviews: subviews)
        for (index, point) in layout.points.enumerated() {
            subviews[index].place(at: CGPoint(x: bounds.minX + point.x, y: bounds.minY + point.y),
                                  proposal: ProposedViewSize(width: layout.sizes[index].width, height: nil))
        }
    }

    private func arrange(width: CGFloat, subviews: Subviews) -> (size: CGSize, points: [CGPoint], sizes: [CGSize]) {
        var x: CGFloat = 0, y: CGFloat = 0, rowHeight: CGFloat = 0, maxWidth: CGFloat = 0
        var points: [CGPoint] = [], sizes: [CGSize] = []
        for subview in subviews {
            var size = subview.sizeThatFits(.unspecified)
            if size.width > width { size = subview.sizeThatFits(ProposedViewSize(width: width, height: nil)) }
            if x > 0, x + size.width > width { x = 0; y += rowHeight + spacing; rowHeight = 0 }
            points.append(CGPoint(x: x, y: y)); sizes.append(size)
            x += size.width + spacing; rowHeight = max(rowHeight, size.height); maxWidth = max(maxWidth, min(width, x - spacing))
        }
        return (CGSize(width: maxWidth, height: y + rowHeight), points, sizes)
    }
}

// MARK: Marks

/// The sparkle that says "your note said this". Decorative; the caption beside it carries the words.
struct LogSparkle: View {
    var reading = false
    @Environment(\.colorScheme) private var scheme
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    var body: some View {
        Image(systemName: "sparkles")
            .font(.footnote.weight(.semibold))
            .foregroundStyle(AdaptiveColors(colorScheme: scheme).noteMark)
            // The system's own symbol effect while a model reads; still under Reduce Motion, and
            // still in the held capture frames (a looping effect keeps the UI-test runner from idling).
            .symbolEffect(.pulse, isActive: reading && !reduceMotion && !LogSheetDebug.instantUnfold)
            .accessibilityHidden(true)
    }
}

// MARK: Sheet chrome

/// `LHSheet` (§1.20) with one difference: the header and the footer are backed by the sheet's own
/// opaque surface, so rows that scroll beneath them (when a row opens or the keyboard rises) never
/// show through the title or the Log button. The spec is `LHSheet`'s: a 56pt header with the title
/// and a `.icon` close at the trailing edge, gutter 20, the pinned footer inset 16. (Blocker note
/// for package A: give `LHSheet` this backing, then this type is deleted.)
struct LogSheetChrome<Content: View, Footer: View>: View {
    let title: String
    var subtitle: String? = nil
    var onClose: () -> Void
    @ViewBuilder var content: Content
    @ViewBuilder var footer: Footer

    @Environment(\.colorScheme) private var colorScheme
    private var colors: AdaptiveColors { AdaptiveColors(colorScheme: colorScheme) }

    var body: some View {
        ScrollView {
            content
                .padding(.horizontal, LHMetrics.gutter)
                .padding(.bottom, 16)
                .frame(maxWidth: .infinity, alignment: .leading)
        }
        .scrollDismissesKeyboard(.interactively)
        .safeAreaInset(edge: .bottom, spacing: 0) {
            // No footer, no inset: an empty one painted an opaque 32pt block over the list.
            if Footer.self != EmptyView.self {
                VStack(spacing: 4) { footer }
                    .padding(.horizontal, 16)
                    .padding(.top, 8)
                    .padding(.bottom, 16)
                    .background(colors.backgroundSecondary.ignoresSafeArea(edges: .bottom))
                    .overlay(alignment: .top) { fade(up: true) }
            }
        }
        // Screen anatomy: the one sheet header (same title face and size as the tabs).
        .lhSheetScreen(title, subtitle: subtitle, onClose: onClose, background: colors.backgroundSecondary)
    }

    /// A short fade where content scrolls under the pinned header or footer, so a line is never
    /// cut flat mid-glyph (Reminders and Things fade here too).
    private func fade(up: Bool) -> some View {
        LinearGradient(colors: [colors.backgroundSecondary.opacity(0), colors.backgroundSecondary],
                       startPoint: up ? .top : .bottom, endPoint: up ? .bottom : .top)
            .frame(height: 14)
            .offset(y: up ? -14 : 14)
            .allowsHitTesting(false)
            .accessibilityHidden(true)
    }
}
