// MARK: Placement (what package J needs)

/// Where Log time is hosted. The compact shell presents it as an opaque `.large` sheet; the
/// two-pane shell (package J) hosts the same content in the right pane, where it is not a sheet.
/// J maps its `PaneContext` to this: `.sheet` → `.sheet`, `.pane` → `.pane`. Log time never
/// checks a width or a size class itself.
///
///   .sheet  `LHSheet` chrome with the drag indicator, the close button and the opaque
///           `backgroundSecondary` surface (`.lhSheetPresentation(.focused)`).
///   .pane   the same `LHSheet` content without the sheet's presentation modifiers and without
///           the drag indicator; the header names the rental shown; `onClose` restores the
///           previous tab (the host's job).
enum LogTimePlacement: Equatable {
    case sheet
    case pane
}

// MARK: Strings

